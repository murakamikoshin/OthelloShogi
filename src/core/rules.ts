/**
 * バランス調整用のパラメータ。
 *
 * ここが「数値の唯一の置き場所」です。盤の広さ・連鎖の上限・反転の距離・持ち駒の枚数は
 * 実際に対局しながら変える前提の値なので、他のファイルに数値を直接書かないこと。
 */
import type { BasePieceType, Color, Hand } from './types.ts';

// ---------------------------------------------------------------------------
// 盤の広さ
// ---------------------------------------------------------------------------

/**
 * 盤の一辺のマス数。ここを変えるだけで盤の広さが変わる
 * （初期配置・棋譜の座標表記・歩の最終段も自動で追従する）。
 *
 * 注意: 棋譜表記が1桁の数字なので 10 未満であること。
 */
export const BOARD_SIZE = 6;

/** 盤のマス総数。 */
export const SQUARE_COUNT = BOARD_SIZE * BOARD_SIZE;

/**
 * 初期配置（先手ぶん）。後手は盤を180度回した位置に同じ駒を置く。
 *
 * 6x6 ならこうなる:
 *
 *     c0 c1 c2 c3 c4 c5
 *   r0  ・ ・ 角 玉 飛 ・   ← 後手
 *   r1  ・ ・ 歩 歩 歩 ・
 *   r2  ・ ・ ・ ・ ・ ・
 *   r3  ・ ・ ・ ・ ・ ・
 *   r4  ・ 歩 歩 歩 ・ ・
 *   r5  ・ 飛 玉 角 ・ ・   ← 先手
 *
 * 盤を空にして始めると、1手目に飛を打つだけで王手がかかってしまい、
 * 受け続けるだけの対局になる。玉に守りを付けることで、
 * 陣形を崩してから攻める将棋らしい流れになり、序盤から駒が接触して反転も起きる。
 */
export const INITIAL_SETUP: readonly { readonly row: number; readonly col: number; readonly type: BasePieceType }[] =
  (() => {
    const mid = Math.floor(BOARD_SIZE / 2);
    const back = BOARD_SIZE - 1;
    return [
      { row: back, col: mid - 1, type: 'K' },
      { row: back, col: mid - 2, type: 'R' },
      { row: back, col: mid, type: 'B' },
      { row: back - 1, col: mid - 2, type: 'P' },
      { row: back - 1, col: mid - 1, type: 'P' },
      { row: back - 1, col: mid, type: 'P' },
    ] as const;
  })();

/**
 * 初期持ち駒。盤の埋まり具合＝反転の起きやすさを決める一番効く数値。
 * 飛と角は初期配置で盤に出したので、持ち駒は1枚ずつ。
 *
 * 先手だけ歩が1枚多い。AI 同士で60局指させたところ先手の勝率が 33% しかなく、
 * 「先に陣形を崩した側が狙われる」という後手有利がはっきり出たため、
 * 先手に持ち駒1枚ぶんのハンデ差を付けている（囲碁のコミに相当）。
 * これで同じ条件の60局で先手勝率 47% になり、ほぼ互角になった。
 */
export const INITIAL_HANDS: Readonly<Record<Color, Hand>> = {
  sente: { P: 4, R: 1, B: 1 },
  gote: { P: 3, R: 1, B: 1 },
};

// ---------------------------------------------------------------------------
// 連鎖反転
// ---------------------------------------------------------------------------

/**
 * 玉に隣接している駒は寝返らないか。
 *
 * true にすると「自分の玉の隣にいる駒は、玉への忠誠を保つので寝返らない」。
 * 挟み判定は、その駒に当たった時点でその方向を打ち切る（相手の玉と同じ扱い）。
 *
 * これが無いと、玉の守り駒が一手で全部寝返って玉が裸になり、
 * 序盤で一方的に玉を取られる対局ばかりになる。
 * 玉のまわりが「安定地帯」になることで、オセロの隅と同じような陣地の取り合いが生まれる。
 */
export const KING_GUARDS_NEIGHBORS = true;

/**
 * 1手番で連鎖できる段数の上限。
 * 1段目（打った駒による反転）も 1 と数える。強すぎるなら 3 まで下げる余地がある。
 */
export const MAX_CHAIN = 5;

/**
 * 挟み判定に使う方向の決め方。
 *
 *   'attack' … 打った駒の利きの方向だけ（歩は前1方向のみ）
 *   'wide'   … 利きの方向 ＋ 縦横4方向。歩でも横で挟めるようになる
 *   'all8'   … 全8方向。駒種による違いが消え、完全にオセロと同じ挟み判定になる
 *
 * 追加された方向は「1マスだけ利く方向」と同じ距離設定（STEP_FLIP_RANGE）で扱う。
 */
export type FlipDirectionMode = 'attack' | 'wide' | 'all8';
export const FLIP_DIRECTION_MODE: FlipDirectionMode = 'all8';

/**
 * 「走る」方向（飛・角・竜・馬の本来の走り）の挟み判定の距離上限。
 * 無制限が既定。強すぎるなら 3 に制限する案がある。
 */
export const SLIDE_FLIP_RANGE = Number.POSITIVE_INFINITY;

/**
 * 「1マスだけ利く」方向（歩の前・と金の6方向・竜の斜め・馬の縦横）の
 * 挟み判定の距離上限。
 *
 * 無制限が既定（オセロと同じ挟み判定）。1 にすると「利きの届く範囲でしか挟めない」
 * という、より将棋寄りの挙動になる。
 */
export const STEP_FLIP_RANGE = Number.POSITIVE_INFINITY;

// ---------------------------------------------------------------------------
// 決着条件
// ---------------------------------------------------------------------------

/** 同一局面がこの回数出現したら駒数判定で決着。 */
export const REPETITION_LIMIT = 4;

/** 両者が連続でこの回数パスしたら駒数判定で決着。 */
export const PASS_LIMIT = 2;
