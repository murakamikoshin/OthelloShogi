/**
 * バランス調整用のパラメータ。
 *
 * ここが「数値の唯一の置き場所」です。盤の広さ・連鎖の上限・反転の距離・持ち駒の枚数は
 * 実際に対局しながら変える前提の値なので、他のファイルに数値を直接書かないこと。
 */
import type { Hand } from './types.ts';

// ---------------------------------------------------------------------------
// 盤の広さ
// ---------------------------------------------------------------------------

/**
 * 盤の一辺のマス数。ここを変えるだけで盤の広さが変わる
 * （初期配置・棋譜の座標表記・歩の最終段も自動で追従する）。
 *
 * 注意: 棋譜表記が1桁の数字なので 10 未満であること。
 */
export const BOARD_SIZE = 6;

/** 盤のマス総数。 */
export const SQUARE_COUNT = BOARD_SIZE * BOARD_SIZE;

/** 先手の玉と歩を置く筋。 */
export const INITIAL_KING_COL_SENTE = Math.floor(BOARD_SIZE / 2) - 1;

/** 後手の玉と歩を置く筋。 */
export const INITIAL_KING_COL_GOTE = Math.floor(BOARD_SIZE / 2);

/** 初期持ち駒（両者共通）。盤の埋まり具合＝連鎖の起きやすさを決める一番効く数値。 */
export const INITIAL_HAND: Hand = { P: 4, R: 2, B: 2 };

// ---------------------------------------------------------------------------
// 連鎖反転
// ---------------------------------------------------------------------------

/**
 * 1手番で連鎖できる段数の上限。
 * 1段目（打った駒による反転）も 1 と数える。強すぎるなら 3 まで下げる余地がある。
 */
export const MAX_CHAIN = 5;

/**
 * 挟み判定に使う方向の決め方。
 *
 *   'attack' … 打った駒の利きの方向だけ（歩は前1方向のみ）
 *   'wide'   … 利きの方向 ＋ 縦横4方向。歩でも横で挟めるようになる
 *   'all8'   … 全8方向。駒種による違いが消え、完全にオセロと同じ挟み判定になる
 *
 * 追加された方向は「1マスだけ利く方向」と同じ距離設定（STEP_FLIP_RANGE）で扱う。
 */
export type FlipDirectionMode = 'attack' | 'wide' | 'all8';
export const FLIP_DIRECTION_MODE: FlipDirectionMode = 'all8';

/**
 * 「走る」方向（飛・角・竜・馬の本来の走り）の挟み判定の距離上限。
 * 無制限が既定。強すぎるなら 3 に制限する案がある。
 */
export const SLIDE_FLIP_RANGE = Number.POSITIVE_INFINITY;

/**
 * 「1マスだけ利く」方向（歩の前・と金の6方向・竜の斜め・馬の縦横）の
 * 挟み判定の距離上限。
 *
 * 無制限が既定（オセロと同じ挟み判定）。1 にすると「利きの届く範囲でしか挟めない」
 * という、より将棋寄りの挙動になる。
 */
export const STEP_FLIP_RANGE = Number.POSITIVE_INFINITY;

// ---------------------------------------------------------------------------
// 決着条件
// ---------------------------------------------------------------------------

/** 同一局面がこの回数出現したら駒数判定で決着。 */
export const REPETITION_LIMIT = 4;

/** 両者が連続でこの回数パスしたら駒数判定で決着。 */
export const PASS_LIMIT = 2;
